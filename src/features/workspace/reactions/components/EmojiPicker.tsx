export interface EmojiPickerProps {
  onEmojiSelect: (emoji: string) => void;
  onClose?: () => void;
}

export const EmojiPicker: React.FC<EmojiPickerProps> = ({ onEmojiSelect, onClose }) => {
  const [searchQuery, setSearchQuery] = useState('');
  const [selectedCategory, setSelectedCategory] = useState<string>('인기');

  const filteredEmojis = useMemo(() => {
    if (!searchQuery.trim()) {
      return EMOJI_CATEGORIES[selectedCategory as keyof typeof EMOJI_CATEGORIES] || [];
    }

    // 모든 카테고리에서 검색
    const allEmojis = Object.values(EMOJI_CATEGORIES).flat();
    return allEmojis.filter((emoji) => {
      // 간단한 검색 (실제로는 이모지 이름으로 검색해야 함)
      return emoji.includes(searchQuery);
    });
  }, [searchQuery, selectedCategory]);

  const handleEmojiClick = (emoji: string) => {
    onEmojiSelect(emoji);
    onClose?.();
  };

  return (
    <div className="w-80 h-96 bg-popover border rounded-lg shadow-lg flex flex-col">
      {/* 헤더 */}
      <div className="flex-shrink-0 p-3 border-b">
        <div className="relative">
          <Search className="absolute left-2 top-1/2 transform -translate-y-1/2 h-4 w-4 text-muted-foreground" />
          <Input
            value={searchQuery}
            onChange={(e) => setSearchQuery(e.target.value)}
            placeholder="이모지 검색..."
            className="pl-8 h-8 text-sm"
          />
          {searchQuery && (
            <Button
              variant="ghost"
              size="icon"
              className="absolute right-1 top-1/2 transform -translate-y-1/2 h-6 w-6"
              onClick={() => setSearchQuery('')}
            >
              <X className="h-3 w-3" />
            </Button>
          )}
        </div>
      </div>

      {/* 카테고리 탭 */}
      {!searchQuery && (
        <div className="flex-shrink-0 flex gap-1 px-2 py-2 border-b overflow-x-auto">
          {Object.keys(EMOJI_CATEGORIES).map((category) => (
            <button
              key={category}
              onClick={() => setSelectedCategory(category)}
              className={cn(
                'px-2 py-1 text-xs rounded-md whitespace-nowrap transition-colors',
                selectedCategory === category
                  ? 'bg-accent text-accent-foreground'
                  : 'text-muted-foreground hover:bg-muted'
              )}
            >
              {category}
            </button>
          ))}
        </div>
      )}

      {/* 이모지 그리드 */}
      <div className="flex-1 overflow-y-auto p-3">
        <div className="grid grid-cols-8 gap-1">
          {filteredEmojis.map((emoji, index) => (
            <button
              key={`${emoji}-${index}`}
              onClick={() => handleEmojiClick(emoji)}
              className="h-8 w-8 flex items-center justify-center rounded-md hover:bg-accent text-lg transition-colors"
              title={emoji}
            >
              {emoji}
            </button>
          ))}
        </div>
      </div>
    </div>
  );
};

